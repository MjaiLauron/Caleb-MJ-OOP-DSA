    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        
    String jobID = txtJobID.getText().trim();
    String customer = txtCustomer.getText().trim();
    String type = cmbType.getSelectedItem().toString();
    String copiesText = txtCopies.getText().trim();

    // Check if fields are empty
    if (jobID.isEmpty() || customer.isEmpty() || copiesText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields.",
            "Missing Information",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Check if Job ID already exists in the waiting queue
    if (queue.searchJob(jobID) != null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Job ID already exists. Please use another ID.",
            "Duplicate Job ID",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int copies;

    // Validate number of copies
    try {
        copies = Integer.parseInt(copiesText);

        if (copies <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Number of copies must be greater than zero.",
                "Invalid Copies",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter a valid whole number for copies.",
            "Invalid Input",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Create the correct print job object
    printJob newJob;

    if (type.equals("Document")) {
        newJob = new printJob.DocumentPrintJob(
            jobID, customer, copies
        );
    } else {
        newJob = new printJob.PhotoPrintJob(
            jobID, customer, copies
        );
    }

    // Add job to queue
    if (queue.addJob(newJob)) {

        // Display the added job in the table
        tableModel.addRow(new Object[]{
            newJob.getJobID(),
            newJob.getCustomerName(),
            newJob.getPrintType(),
            newJob.getCopies()
        });

        lblStatus.setText("Print job added successfully!");

        clearFields();

    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "The print queue is full.",
            "Queue Full",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDisplayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayActionPerformed
        // TODO add your handling code here:

    // Clear the existing table rows
    tableModel.setRowCount(0);

    // Get all waiting jobs from the queue
    printJob[] waitingJobs = queue.getWaitingJobs();

    // Display each waiting job
    for (int i = 0; i < waitingJobs.length; i++) {

        printJob job = waitingJobs[i];

        tableModel.addRow(new Object[]{
            job.getJobID(),
            job.getCustomerName(),
            job.getPrintType(),
            job.getCopies()
        });
    }

    lblStatus.setText(
        "Displaying " + waitingJobs.length + " waiting job(s)."
    );
    }//GEN-LAST:event_btnDisplayActionPerformed

    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        // Check if the queue is empty
    if (queue.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "There are no print jobs to process.",
            "Empty Queue",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        lblStatus.setText("No waiting print jobs.");
        return;
    }

    // Process the first job in the queue
    printJob processedJob = queue.processNextJob();

    // Remove the processed job from the table
    tableModel.removeRow(0);

    // Display the processed job information
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Print job successfully processed!\n\n"
        + "Job ID: " + processedJob.getJobID() + "\n"
        + "Customer: " + processedJob.getCustomerName() + "\n"
        + "Print Type: " + processedJob.getPrintType() + "\n"
        + "Copies: " + processedJob.getCopies(),
        "Job Processed",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    lblStatus.setText(
        "Successfully processed Job ID: " + processedJob.getJobID()
    );
    }//GEN-LAST:event_btnProcessActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
          // Get the Job ID entered by the user
    String searchID = txtSearch.getText().trim();

    // Check if the search field is empty
    if (searchID.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter a Job ID to search.",
            "Empty Search",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Search for the job in the queue
    printJob foundJob = queue.searchJob(searchID);

    // Check if the job was found
    if (foundJob != null) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Print job found!\n\n"
            + "Job ID: " + foundJob.getJobID() + "\n"
            + "Customer: " + foundJob.getCustomerName() + "\n"
            + "Print Type: " + foundJob.getPrintType() + "\n"
            + "Copies: " + foundJob.getCopies(),
            "Search Result",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        lblStatus.setText("Found Job ID: " + foundJob.getJobID());

    } else {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No waiting print job found with ID: " + searchID,
            "Job Not Found",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        lblStatus.setText("Job ID not found.");
    }
    }//GEN-LAST:event_btnSearchActionPerformed

